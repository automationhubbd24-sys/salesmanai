async function ensureInstagramColumns() {
    await pgClient.query(`
        CREATE TABLE IF NOT EXISTS page_access_token_message (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            page_id TEXT UNIQUE NOT NULL,
            name TEXT,
            page_access_token TEXT,
            email TEXT,
            user_id TEXT,
            ai TEXT,
            chat_model TEXT,
            cheap_engine BOOLEAN DEFAULT TRUE,
            subscription_status TEXT DEFAULT 'active'
        );
        CREATE TABLE IF NOT EXISTS fb_message_database (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            page_id TEXT UNIQUE NOT NULL,
            text_prompt TEXT,
            wait INTEGER DEFAULT 5,
            image_send BOOLEAN DEFAULT TRUE,
            image_detection BOOLEAN DEFAULT TRUE,
            template BOOLEAN DEFAULT TRUE,
            reply_message BOOLEAN DEFAULT TRUE,
            order_tracking BOOLEAN DEFAULT TRUE
        );
        CREATE TABLE IF NOT EXISTS fb_chats (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            page_id TEXT,
            sender_id TEXT,
            recipient_id TEXT,
            message_id TEXT UNIQUE,
            text TEXT,
            timestamp BIGINT,
            status TEXT,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
            reply_by TEXT,
            ai_model TEXT
        );
    `);
    await pgClient.query(`ALTER TABLE page_access_token_message ADD COLUMN IF NOT EXISTS platform text NOT NULL DEFAULT 'messenger'`);
    await pgClient.query(`ALTER TABLE page_access_token_message ADD COLUMN IF NOT EXISTS user_id text`);
    await pgClient.query(`ALTER TABLE fb_message_database ADD COLUMN IF NOT EXISTS platform text NOT NULL DEFAULT 'messenger'`);
    await pgClient.query(`ALTER TABLE fb_chats ADD COLUMN IF NOT EXISTS platform text NOT NULL DEFAULT 'messenger'`);
}

const getAccount = async (accountId, userId) => {
    await ensureInstagramColumns();
    const { rows } = await pgClient.query(
        `SELECT p.*, d.id AS db_id
         FROM page_access_token_message p
         LEFT JOIN fb_message_database d ON d.page_id = p.page_id AND d.platform = 'instagram'
         WHERE p.page_id = $1 AND p.platform = 'instagram' AND p.user_id::text = $2
         LIMIT 1`,
        [String(accountId), String(userId)]
    );
    return rows[0] || null;
};

async function saveInstagramAccount({ accountId, name, pageAccessToken, email, userId }) {
    await ensureInstagramColumns();
    await pgClient.query(
        `INSERT INTO page_access_token_message (page_id, name, page_access_token, email, user_id, platform, ai, chat_model, cheap_engine, subscription_status)
         VALUES ($1, $2, $3, $4, $5, 'instagram', 'gemini', 'gemini-2.0-flash', true, 'active')
         ON CONFLICT (page_id) DO UPDATE SET
           name = EXCLUDED.name,
           page_access_token = EXCLUDED.page_access_token,
           email = EXCLUDED.email,
           user_id = EXCLUDED.user_id,
           platform = 'instagram'`,
        [String(accountId), name, pageAccessToken, String(email || '').toLowerCase(), userId]
    );

    const result = await pgClient.query(
        `INSERT INTO fb_message_database (page_id, platform, text_prompt, wait, image_send, image_detection, template, reply_message, order_tracking)
         VALUES ($1, 'instagram', $2, 5, true, true, true, true, true)
         ON CONFLICT (page_id) DO UPDATE SET platform = 'instagram'
         RETURNING id`,
        [String(accountId), 'You are a helpful Instagram sales assistant.']
    );

    return result.rows[0]?.id || null;
}

async function subscribePageForInstagram(pageId, pageAccessToken) {
    const fields = ['messages', 'messaging_postbacks', 'message_deliveries', 'message_reads', 'message_echoes'];
    try {
        await axios.post(`https://graph.facebook.com/${GRAPH_VERSION}/${pageId}/subscribed_apps`, null, {
            params: { access_token: pageAccessToken, subscribed_fields: fields.join(',') },
            timeout: 15000
        });
        return true;
    } catch (error) {
        console.warn(`[Instagram Auto Connect] Page subscription failed for ${pageId}:`, error.response?.data?.error?.message || error.message);
        return false;
    }
}

