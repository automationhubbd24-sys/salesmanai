router.post('/send', authMiddleware, upload.single('image'), async (req, res) => {
    try {
        const account = await getAccount(req.body?.accountId || req.body?.pageId, req.user.id);
        const to = String(req.body?.to || '');
        const message = String(req.body?.message || '').trim();
        if (!account || !to || (!message && !req.file)) return res.status(400).json({ error: 'accountId, to and message or image are required' });

        const sent = [];
        if (req.file) {
            const baseUrl = process.env.PUBLIC_BASE_URL || process.env.BACKEND_URL || `${req.protocol}://${req.get('host')}`;
            const imageUrl = await imageService.uploadProductImage(req.file.buffer, req.file.mimetype, `smart-inbox/instagram/${account.page_id}`, baseUrl);
            const response = await instagramService.sendImage(account.page_id, to, imageUrl, account.page_access_token);
            const id = response?.message_id || `instagram_admin_image_${Date.now()}`;
            await dbService.saveInstagramChat({ instagram_account_id: account.page_id, sender_id: account.page_id, recipient_id: to, message_id: id, text: `[Image URL]: ${imageUrl}${message ? `\n${message}` : ''}`, timestamp: Date.now(), status: 'sent', reply_by: 'admin' });
            sent.push({ messageId: id, imageUrl });
        }
        if (message) {
            const response = await instagramService.sendMessage(account.page_id, to, message, account.page_access_token);
            const id = response?.message_id || `instagram_admin_${Date.now()}`;
            await dbService.saveInstagramChat({ instagram_account_id: account.page_id, sender_id: account.page_id, recipient_id: to, message_id: id, text: message, timestamp: Date.now(), status: 'sent', reply_by: 'admin' });
            sent.push({ messageId: id, body: message });
        }
        res.json({
            success: true,
            message: {
                message_id: sent[0]?.messageId || null,
                from: 'me',
                body: sent.map((part) => part.body).filter(Boolean).join('\n\n'),
                timestamp: Date.now(),
                reply_by: 'admin',
                is_ai: false
            },
            sent
        });
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
});

