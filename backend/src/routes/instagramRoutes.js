router.post('/pages/auto-connect', authMiddleware, async (req, res) => {
    try {
        const { accessToken } = req.body || {};
        if (!accessToken) return res.status(400).json({ error: 'accessToken is required' });

        const pagesResponse = await axios.get(`https://graph.facebook.com/${GRAPH_VERSION}/me/accounts`, {
            params: {
                fields: 'id,name,access_token,instagram_business_account{id,username,name}',
                access_token: accessToken
            },
            timeout: 20000
        });

        const pages = Array.isArray(pagesResponse.data?.data) ? pagesResponse.data.data : [];
        const connected = [];
        const skipped = [];

        for (const page of pages) {
            const ig = page.instagram_business_account;
            if (!ig?.id || !page.access_token) {
                skipped.push({ page_id: page.id, page_name: page.name, reason: 'No linked Instagram Professional account' });
                continue;
            }

            const dbId = await saveInstagramAccount({
                accountId: ig.id,
                name: ig.username || ig.name || `${page.name} Instagram`,
                pageAccessToken: page.access_token,
                email: req.user.email,
                userId: req.user.id
            });
            const subscribed = await subscribePageForInstagram(page.id, page.access_token);
            connected.push({ page_id: ig.id, name: ig.username || ig.name || `${page.name} Instagram`, db_id: dbId, facebook_page_id: page.id, subscribed });
        }

        res.json({ success: true, connected, skipped });
    } catch (error) {
        res.status(400).json({ error: error.response?.data?.error?.message || error.message });
    }
});

router.post('/pages/manual', authMiddleware, async (req, res) => {
    try {
        const { page_id, name, page_access_token, email } = req.body || {};
        if (!page_id || !name || !page_access_token) return res.status(400).json({ error: 'page_id, name and page_access_token are required' });

        const verified = await axios.get(`https://graph.facebook.com/${GRAPH_VERSION}/${page_id}`, {
            params: { fields: 'id,username,name', access_token: page_access_token },
            timeout: 15000
        });
        if (String(verified.data?.id) !== String(page_id)) return res.status(400).json({ error: 'Instagram account ID does not match the access token' });

        const dbId = await saveInstagramAccount({
            accountId: page_id,
            name: verified.data.username || verified.data.name || name,
            pageAccessToken: page_access_token,
            email: email || req.user.email,
            userId: req.user.id
        });

        res.json({ success: true, id: dbId, db_id: dbId });
    } catch (error) {
        res.status(400).json({ error: error.response?.data?.error?.message || error.message });
    }
});

