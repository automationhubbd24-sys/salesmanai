async function ensureInstagramTables() {
    await pgClient.query(`
        CREATE TABLE IF NOT EXISTS instagram_accounts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            instagram_account_id TEXT NOT NULL,
            instagram_username TEXT,
            name TEXT,
            facebook_page_id TEXT,
            page_access_token TEXT,
            user_access_token TEXT,
            email TEXT,
            user_id TEXT,
            ai TEXT DEFAULT 'gemini',
            chat_model TEXT DEFAULT 'gemini-2.0-flash',
            cheap_engine BOOLEAN DEFAULT TRUE,
            subscription_status TEXT DEFAULT 'active',
            created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
            updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
            UNIQUE(user_id, instagram_account_id)
        );

        CREATE TABLE IF NOT EXISTS instagram_message_database (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            instagram_account_id TEXT NOT NULL UNIQUE,
            user_id TEXT,
            text_prompt TEXT,
            wait INTEGER DEFAULT 5,
            image_send BOOLEAN DEFAULT TRUE,
            image_detection BOOLEAN DEFAULT TRUE,
            template BOOLEAN DEFAULT TRUE,
            reply_message BOOLEAN DEFAULT TRUE,
            order_tracking BOOLEAN DEFAULT TRUE,
            swipe_reply BOOLEAN DEFAULT FALSE,
            audio_detection BOOLEAN DEFAULT FALSE,
            block_emoji TEXT DEFAULT '',
            unblock_emoji TEXT DEFAULT '',
            image_prompt TEXT DEFAULT '',
            check_conversion INTEGER DEFAULT 20,
            temperature NUMERIC DEFAULT 0.7,
            top_p NUMERIC DEFAULT 0.9,
            ai TEXT,
            api_key TEXT,
            chat_model TEXT,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
            updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
        );

        CREATE TABLE IF NOT EXISTS instagram_chats (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            instagram_account_id TEXT,
            sender_id TEXT,
            recipient_id TEXT,
            message_id TEXT UNIQUE,
            text TEXT,
            timestamp BIGINT,
            status TEXT DEFAULT 'pending',
            created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
            reply_by TEXT,
            token INTEGER DEFAULT 0,
            ai_model TEXT,
            sender_name TEXT
        );

        CREATE TABLE IF NOT EXISTS instagram_order_tracking (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            instagram_account_id TEXT,
            sender_id TEXT,
            status TEXT,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
            updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
        );

        CREATE INDEX IF NOT EXISTS idx_instagram_accounts_user ON instagram_accounts(user_id);
        CREATE INDEX IF NOT EXISTS idx_instagram_chats_account_sender ON instagram_chats(instagram_account_id, sender_id);
        CREATE INDEX IF NOT EXISTS idx_instagram_orders_account_sender ON instagram_order_tracking(instagram_account_id, sender_id);
    `);
}

function mapAccount(row) {
    if (!row) return null;
    return {
        ...row,
        page_id: row.instagram_account_id,
        db_id: row.db_id,
        page_access_token: row.page_access_token
    };
}

async function migrateLegacyInstagramRows(userId) {
    const { rows } = await pgClient.query(
        `SELECT p.page_id, p.name, p.page_access_token, p.email, p.user_id, p.ai, p.chat_model, p.cheap_engine, p.subscription_status,
                d.id AS old_db_id, d.text_prompt, d.wait, d.image_send, d.image_detection, d.template, d.reply_message, d.order_tracking,
                d.swipe_reply, d.audio_detection, d.block_emoji, d.unblock_emoji, d.image_prompt, d.check_conversion, d.temperature, d.top_p
         FROM page_access_token_message p
         LEFT JOIN fb_message_database d ON d.page_id = p.page_id AND d.platform = 'instagram'
         WHERE p.platform = 'instagram' AND p.user_id::text = $1`,
        [String(userId)]
    ).catch(() => ({ rows: [] }));

    for (const row of rows) {
        await saveInstagramAccount({
            accountId: row.page_id,
            username: row.name,
            name: row.name,
            pageAccessToken: row.page_access_token,
            userAccessToken: null,
            facebookPageId: null,
            email: row.email,
            userId: row.user_id,
            config: row
        });
    }
}

async function getAccount(accountId, userId) {
    await ensureInstagramTables();
    const { rows } = await pgClient.query(
        `SELECT a.*, d.id AS db_id
         FROM instagram_accounts a
         LEFT JOIN instagram_message_database d ON d.instagram_account_id = a.instagram_account_id
         WHERE a.instagram_account_id = $1 AND a.user_id::text = $2
         LIMIT 1`,
        [String(accountId), String(userId)]
    );
    return mapAccount(rows[0]);
}

async function saveInstagramAccount({ accountId, username, name, pageAccessToken, userAccessToken, facebookPageId, email, userId, config = {} }) {
    await ensureInstagramTables();
    await pgClient.query(
        `INSERT INTO instagram_accounts
            (instagram_account_id, instagram_username, name, facebook_page_id, page_access_token, user_access_token, email, user_id, ai, chat_model, cheap_engine, subscription_status)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8, COALESCE($9, 'gemini'), COALESCE($10, 'gemini-2.0-flash'), COALESCE($11, TRUE), COALESCE($12, 'active'))
         ON CONFLICT (user_id, instagram_account_id) DO UPDATE SET
            instagram_username = EXCLUDED.instagram_username,
            name = EXCLUDED.name,
            facebook_page_id = EXCLUDED.facebook_page_id,
            page_access_token = EXCLUDED.page_access_token,
            user_access_token = COALESCE(EXCLUDED.user_access_token, instagram_accounts.user_access_token),
            email = EXCLUDED.email,
            ai = COALESCE(instagram_accounts.ai, EXCLUDED.ai),
            chat_model = COALESCE(instagram_accounts.chat_model, EXCLUDED.chat_model),
            cheap_engine = COALESCE(instagram_accounts.cheap_engine, EXCLUDED.cheap_engine),
            subscription_status = COALESCE(instagram_accounts.subscription_status, EXCLUDED.subscription_status),
            updated_at = NOW()`,
        [
            String(accountId),
            username || null,
            name || username || `Instagram ${accountId}`,
            facebookPageId ? String(facebookPageId) : null,
            pageAccessToken,
            userAccessToken || null,
            String(email || '').toLowerCase(),
            String(userId),
            config.ai,
            config.chat_model,
            config.cheap_engine,
            config.subscription_status
        ]
    );

    const result = await pgClient.query(
        `INSERT INTO instagram_message_database
            (instagram_account_id, user_id, text_prompt, wait, image_send, image_detection, template, reply_message, order_tracking,
             swipe_reply, audio_detection, block_emoji, unblock_emoji, image_prompt, check_conversion, temperature, top_p, ai, chat_model)
         VALUES ($1, $2, $3, COALESCE($4, 5), COALESCE($5, TRUE), COALESCE($6, TRUE), COALESCE($7, TRUE), COALESCE($8, TRUE), COALESCE($9, TRUE),
             COALESCE($10, FALSE), COALESCE($11, FALSE), COALESCE($12, ''), COALESCE($13, ''), COALESCE($14, ''), COALESCE($15, 20), COALESCE($16, 0.7), COALESCE($17, 0.9), $18, $19)
         ON CONFLICT (instagram_account_id) DO UPDATE SET
            user_id = EXCLUDED.user_id,
            updated_at = NOW()
         RETURNING id`,
        [
            String(accountId),
            String(userId),
            config.text_prompt || 'You are a helpful Instagram sales assistant.',
            config.wait,
            config.image_send,
            config.image_detection,
            config.template,
            config.reply_message,
            config.order_tracking,
            config.swipe_reply,
            config.audio_detection,
            config.block_emoji,
            config.unblock_emoji,
            config.image_prompt,
            config.check_conversion,
            config.temperature,
            config.top_p,
            config.ai,
            config.chat_model
        ]
    );

    return result.rows[0]?.id || null;
}

