router.get('/messages/:accountId/:senderId', authMiddleware, async (req, res) => {
    try {
        const account = await getAccount(req.params.accountId, req.user.id);
        if (!account) return res.status(404).json({ error: 'Instagram account not found' });
        const limit = Math.min(Math.max(parseInt(req.query.limit, 10) || 40, 10), 120);
        const offset = Math.max(parseInt(req.query.offset, 10) || 0, 0);
        const { rows } = await pgClient.query(
            `SELECT CASE WHEN reply_by IN ('bot','admin') THEN 'me' ELSE sender_id END AS from, text AS body,
                    COALESCE(timestamp, EXTRACT(EPOCH FROM created_at) * 1000) AS timestamp, reply_by, (reply_by = 'bot') AS is_ai
             FROM fb_chats
             WHERE page_id = $1 AND platform = 'instagram' AND (sender_id = $2 OR recipient_id = $2)
             ORDER BY COALESCE(timestamp, EXTRACT(EPOCH FROM created_at) * 1000) ASC LIMIT $3 OFFSET $4`,
            [account.page_id, req.params.senderId, limit, offset]
        );
        res.json(rows);
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
});

