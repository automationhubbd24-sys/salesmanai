router.get('/pages', authMiddleware, async (req, res) => {
    try {
        await ensureInstagramTables();
        let result = await pgClient.query(
            `SELECT a.instagram_account_id AS page_id, a.instagram_account_id, a.instagram_username, a.name, a.facebook_page_id, d.id AS db_id
             FROM instagram_accounts a
             LEFT JOIN instagram_message_database d ON d.instagram_account_id = a.instagram_account_id
             WHERE a.user_id::text = $1
             ORDER BY a.instagram_account_id DESC`,
            [String(req.user.id)]
        );

        if (result.rows.length === 0) {
            await migrateLegacyInstagramRows(req.user.id);
            result = await pgClient.query(
                `SELECT a.instagram_account_id AS page_id, a.instagram_account_id, a.instagram_username, a.name, a.facebook_page_id, d.id AS db_id
                 FROM instagram_accounts a
                 LEFT JOIN instagram_message_database d ON d.instagram_account_id = a.instagram_account_id
                 WHERE a.user_id::text = $1
                 ORDER BY a.instagram_account_id DESC`,
                [String(req.user.id)]
            );
        }

        res.json(result.rows);
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
});

router.post('/pages/auto-connect', authMiddleware, async (req, res) => {
    try {
        const { accessToken } = req.body || {};
        if (!accessToken) return res.status(400).json({ error: 'accessToken is required' });

        const pages = await instagramService.fetchLinkedInstagramAccounts(accessToken);
        const connected = [];
        const skipped = [];

        for (const page of pages) {
            const ig = page.instagram_business_account;
            if (!ig?.id || !page.access_token) {
                skipped.push({ page_id: page.id, page_name: page.name, reason: 'No linked Instagram Professional account' });
                continue;
            }

            const dbId = await saveInstagramAccount({
                accountId: ig.id,
                username: ig.username,
                name: ig.username || ig.name || `${page.name} Instagram`,
                pageAccessToken: page.access_token,
                userAccessToken: accessToken,
                facebookPageId: page.id,
                email: req.user.email,
                userId: req.user.id
            });
            const subscribed = await instagramService.subscribeLinkedPage(page.id, page.access_token);
            connected.push({
                page_id: ig.id,
                instagram_account_id: ig.id,
                instagram_username: ig.username || null,
                name: ig.username || ig.name || `${page.name} Instagram`,
                db_id: dbId,
                facebook_page_id: page.id,
                subscribed
            });
        }

        res.json({ success: true, connected, skipped });
    } catch (error) {
        res.status(400).json({ error: error.response?.data?.error?.message || error.message });
    }
});

