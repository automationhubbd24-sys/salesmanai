function bool(value) {
  return value === true || value === 'true' || value === 1 || value === '1';
}

function normalizeKeywords(value) {
  const list = Array.isArray(value) ? value : String(value || '').split(/[\n,]/);
  return [...new Set(list.map((item) => String(item || '').trim().toLowerCase()).filter(Boolean))];
}

function normalizeHideMode(value) {
  const mode = String(value || 'keyword_or_ai').trim();
  return HIDE_MODES.has(mode) ? mode : 'keyword_or_ai';
}

function keywordMatches(commentText, keywords) {
  const normalizedText = String(commentText || '').toLowerCase();
  return normalizeKeywords(keywords).filter((keyword) => normalizedText.includes(keyword));
}

function parseHideDecision(value) {
  const rawValue = typeof value === 'string' ? value : (value?.output ?? value?.hide ?? value?.reply ?? value?.text ?? value?.response ?? value?.message ?? '');
  if (typeof rawValue === 'boolean') return { hide: rawValue, reason: rawValue ? 'ai_true' : 'ai_false' };

  const cleaned = String(rawValue || '').replace(/```json|```/gi, '').trim();
  const lowered = cleaned.toLowerCase();
  if (['true', 'yes', 'hide'].includes(lowered)) return { hide: true, reason: 'ai_true' };
  if (['false', 'no', 'skip', 'do not hide'].includes(lowered)) return { hide: false, reason: 'ai_false' };

  try {
    const parsed = JSON.parse(cleaned.match(/\{[\s\S]*\}/)?.[0] || cleaned);
    const decision = parsed.hide ?? parsed.hidden ?? parsed.output ?? parsed.shouldHide ?? parsed.should_hide;
    if (typeof decision === 'boolean') return { hide: decision, reason: String(parsed.reason || (decision ? 'ai_true' : 'ai_false')).slice(0, 250) };
    if (typeof decision === 'string') {
      const normalized = decision.trim().toLowerCase();
      if (['true', 'yes', 'hide'].includes(normalized)) return { hide: true, reason: String(parsed.reason || 'ai_true').slice(0, 250) };
      if (['false', 'no', 'skip', 'do not hide'].includes(normalized)) return { hide: false, reason: String(parsed.reason || 'ai_false').slice(0, 250) };
    }
  } catch (_) {
    if (/\bhide\b/.test(lowered) && !/\b(no|not|false|skip)\b/.test(lowered)) {
      return { hide: true, reason: 'ai_text_hide' };
    }
  }
  return { hide: false, reason: 'ai_parse_failed' };
}

function normalizeObfuscatedText(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/[._\-\s]+/g, '')
    .replace(/[@]/g, 'a')
    .replace(/[0]/g, 'o')
    .replace(/[1!|]/g, 'i')
    .replace(/[3]/g, 'e')
    .replace(/[4]/g, 'a')
    .replace(/[5$]/g, 's')
    .replace(/[7]/g, 't');
}

function normalizeRepeatSignature(value) {
  return normalizeObfuscatedText(value)
    .replace(/[^a-z0-9\u0980-\u09ff]+/g, '')
    .slice(0, 500);
}

function isSameRepeatComment(a, b) {
  const left = normalizeRepeatSignature(a);
  const right = normalizeRepeatSignature(b);
  if (!left || !right) return false;
  if (left === right) return true;
  const longer = left.length >= right.length ? left : right;
  const shorter = left.length >= right.length ? right : left;
  return shorter.length >= 12 && longer.includes(shorter);
}

async function findRepeatedComment({ platform, accountId, postId, commenterId, commentId, commentText }) {
  const { rows } = await pgClient.query(
    `SELECT comment_id, comment_text, created_at
     FROM comment_automation_events
     WHERE platform = $1
       AND account_id = $2
       AND post_id = $3
       AND commenter_id = $4
       AND comment_id <> $5
       AND created_at >= NOW() - INTERVAL '30 days'
     ORDER BY created_at ASC
     LIMIT 100`,
    [platform, String(accountId), String(postId), String(commenterId), String(commentId)]
  );
  const repeats = rows.filter((row) => isSameRepeatComment(row.comment_text, commentText));
  return { isRepeat: repeats.length > 0, repeatCount: repeats.length + 1, firstCommentId: repeats[0]?.comment_id || null };
}

