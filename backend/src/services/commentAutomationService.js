async function syncFacebookPosts(platform, accountId, accessToken) {
  await ensureTables();
  if (platform !== 'messenger') return { synced: 0, posts: [] };
  const posts = await facebookService.listPagePosts(accountId, accessToken, { limit: 10, maxPages: 5 });
  const saved = [];
  for (const post of posts) {
    const existing = await pgClient.query(
      `SELECT * FROM social_post_product_mappings WHERE platform = $1 AND account_id = $2 AND post_id = $3 LIMIT 1`,
      [platform, String(accountId), String(post.id)]
    );
    const current = existing.rows[0] || {};
    saved.push(await upsertMapping(platform, accountId, {
      post_id: post.id,
      caption: post.message || post.story || current.caption || '',
      media_url: post.full_picture || post.picture || current.media_url || '',
      permalink_url: post.permalink_url || current.permalink_url || '',
      product_ids: current.product_ids || [],
      is_active: current.is_active !== undefined ? current.is_active : true,
      auto_like: Boolean(current.auto_like),
      auto_like_children_comment: Boolean(current.auto_like_children_comment),
      auto_reply: Boolean(current.auto_reply),
      auto_reply_children_comment: Boolean(current.auto_reply_children_comment),
      auto_hidden: Boolean(current.auto_hidden),
      auto_comment: Boolean(current.auto_comment),
      prompt_comment: current.prompt_comment || DEFAULT_PROMPT_COMMENT,
      hide_keywords: current.hide_keywords || [],
      hide_ai_instruction: current.hide_ai_instruction || '',
      hide_ai_enabled: Boolean(current.hide_ai_enabled),
      hide_match_mode: current.hide_match_mode || 'keyword_or_ai',
      post_created_at: post.created_time || current.post_created_at || null
    }));
  }
  return { synced: saved.length, posts: saved };
}

async function findPostContext(platform, accountId, postId) {
  await ensureTables();
  const { rows } = await pgClient.query(`SELECT * FROM social_post_product_mappings WHERE platform = $1 AND account_id = $2 AND post_id = $3 AND is_active = TRUE LIMIT 1`, [platform, String(accountId), String(postId)]);
  let mapping = rows[0] || null;
  if (!mapping && platform === 'messenger') {
    const ad = await dbService.getAdContext(postId, accountId).catch(() => null);
    if (ad) mapping = { post_id: postId, caption: ad.description, product_ids: Array.isArray(ad.linked_product_ids) ? ad.linked_product_ids : [] };
  }
  const products = [];
  for (const id of mapping?.product_ids || []) {
    const product = await dbService.getProductById(id).catch(() => null);
    if (product) products.push(product);
  }
  return { mapping, products };
}

function productSummary(products) {
  if (!products.length) return 'No mapped product found for this post.';
  return products.map((product) => `Product ID: ${product.id}\nName: ${product.name}\nPrice: ${product.price || ''} ${product.currency || ''}\nDescription: ${product.description || ''}`).join('\n\n');
}

function buildReplyPrompt({ platform, postId, commentText, context, products, systemPrompt, isReplyComment }) {
  return `${systemPrompt}\n\n${context.mapping?.prompt_comment || DEFAULT_PROMPT_COMMENT}\n\nReturn only the reply text.\n\n<context>\nPlatform: ${platform}\nPost ID: ${postId}\nIs reply/child comment: ${isReplyComment ? 'yes' : 'no'}\nPost caption: ${context.mapping?.caption || ''}\nCustomer comment: ${commentText}\nMapped products:\n${productSummary(products)}\n</context>`;
}

function cleanReply(value) {
  const text = typeof value === 'string' ? value : (value?.reply_text || value?.reply || value?.message || value?.response || '');
  return String(text || '').replace(/```[\s\S]*?```/g, '').trim().slice(0, MAX_PUBLIC_REPLY_LENGTH);
}

async function evaluateHideRules({ config, mapping, commentText, postId, isReplyComment, accountConfig, platform, accountId, commenterId }) {
  const mode = normalizeHideMode(mapping?.hide_match_mode);
  if (!mapping?.auto_hidden) return { shouldHide: false, reason: 'hide_disabled', matchedKeywords: [], mode, aiHide: false, aiReason: '' };
  if (mode === 'all') return { shouldHide: true, reason: 'all_comments', matchedKeywords: [], mode, aiHide: false, aiReason: '' };

  const keywords = normalizeKeywords([...(config?.hide_keywords || []), ...(mapping?.hide_keywords || [])]);
  const matchedKeywords = keywordMatches(commentText, keywords);
  const keywordHide = matchedKeywords.length > 0;
  const aiEnabled = mode !== 'keyword_only' && (Boolean(config?.hide_ai_enabled) || Boolean(mapping?.hide_ai_enabled));
  let aiHide = false;
  let aiReason = '';

  if (aiEnabled) {
    try {
      const result = await aiService.generateResponse({
        pageId: accountId,
        userId: commenterId || 'comment_moderation',
        userMessage: buildHidePrompt({
          commentText,
          postId,
          isReplyComment,
          caption: mapping?.caption || '',
          globalInstruction: config?.hide_ai_instruction || '',
          postInstruction: mapping?.hide_ai_instruction || '',
          matchedKeywords
        }),
        history: [],
        imageUrls: [],
        audioUrls: [],
        config: { ...accountConfig, text_prompt: 'Return only moderation JSON.' },
        platform
      });
      const parsed = parseHideDecision(result);
      aiHide = parsed.hide;
      aiReason = parsed.reason;
    } catch (error) {
      aiReason = `ai_error: ${error.message}`;
    }
  }

  const shouldHide = mode === 'keyword_only' ? keywordHide : mode === 'ai_only' ? aiHide : keywordHide || aiHide;
  return {
    shouldHide,
    reason: shouldHide ? (keywordHide ? 'keyword_match' : 'ai_hide') : 'no_rule_match',
    matchedKeywords,
    mode,
    aiHide,
    aiReason
  };
}

async function updateEvent(platform, commentId, values) {
  await pgClient.query(
    `UPDATE comment_automation_events SET public_reply_status = $1, dm_status = $2, reaction_status = $3, reaction_type = $4, moderation_status = $5, public_reply_text = $6, dm_text = $7, decision = $8, error_message = $9, updated_at = NOW() WHERE platform = $10 AND comment_id = $11`,
    [values.publicStatus, values.dmStatus || 'skipped', values.reactionStatus, values.reactionType || null, values.moderationStatus || 'skipped', values.publicReplyText || null, null, JSON.stringify(values.decision || {}), values.errors?.join(' | ') || null, platform, commentId]
  );
}

async function processCommentAutomationEvent(event) {
  const platform = String(event.platform || '');
  const accountId = String(event.accountId || '');
  const commentId = String(event.commentId || '');
  const commenterId = String(event.commenterId || '');
  const postId = String(event.postId || '');
  const parentId = String(event.parentId || postId);
  const commentText = String(event.commentText || '').trim();
  const accessToken = event.accessToken;
  const isReplyComment = Boolean(event.isReplyComment ?? (parentId && postId && parentId !== postId));
  if (!platform || !accountId || !commentId || !commenterId || !postId || !accessToken) return { skipped: true, reason: 'missing_required_fields' };

  const config = await getConfig(platform, accountId);
  if (!config?.enabled) return { skipped: true, reason: 'disabled' };
  const existing = await pgClient.query(`SELECT id FROM comment_automation_events WHERE platform = $1 AND comment_id = $2 LIMIT 1`, [platform, commentId]);
  if (existing.rows[0]) return { skipped: true, reason: 'duplicate_comment' };

  const context = await findPostContext(platform, accountId, postId);
  const mapping = context.mapping;
  if (!mapping?.is_active) return { skipped: true, reason: 'post_not_configured' };

  const productIds = context.products.map((product) => String(product.id));
  await pgClient.query(`INSERT INTO comment_automation_events (platform, account_id, post_id, comment_id, commenter_id, comment_text, product_ids, is_reply_comment) VALUES ($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT (platform, comment_id) DO NOTHING`, [platform, accountId, postId, commentId, commenterId, commentText, productIds, isReplyComment]);

  const shouldLike = Boolean(mapping.auto_like) && (!isReplyComment || Boolean(mapping.auto_like_children_comment));
  const shouldReply = Boolean(mapping.auto_reply) && (!isReplyComment || Boolean(mapping.auto_reply_children_comment));
  const hideDecision = await evaluateHideRules({ config, mapping, commentText, postId, isReplyComment, accountConfig: event.accountConfig, platform, accountId, commenterId });
  const shouldHide = hideDecision.shouldHide;
  const errors = [];
  let publicStatus = 'skipped';
  let reactionStatus = 'skipped';
  let moderationStatus = 'skipped';
  let publicReplyText = '';

  const decision = {
    action: shouldHide ? 'MODERATE' : shouldReply || shouldLike ? 'ENGAGE' : 'SKIP',
    auto_like: shouldLike,
    auto_reply: shouldReply,
    auto_hidden: shouldHide,
    auto_comment: Boolean(mapping.auto_comment),
    hide_mode: hideDecision.mode,
    hide_reason: hideDecision.reason,
    hide_matched_keywords: hideDecision.matchedKeywords,
    hide_ai_enabled: Boolean(config.hide_ai_enabled) || Boolean(mapping.hide_ai_enabled),
    hide_ai_reason: hideDecision.aiReason,
    reason: 'n8n_style_post_toggle_flow'
  };

  if (shouldLike) {
    try {
      await facebookService.likeComment(commentId, accessToken);
      reactionStatus = 'sent';
    } catch (error) {
      reactionStatus = 'failed';
      errors.push(`like: ${error.message}`);
    }
  }

  if (shouldHide) {
    try {
      await facebookService.hideComment(commentId, accessToken, true);
      moderationStatus = 'hidden';
    } catch (error) {
      moderationStatus = 'failed';
      errors.push(`hide: ${error.message}`);
    }
  }

  if (shouldReply) {
    try {
      const result = await aiService.generateResponse({
        pageId: accountId,
        userId: commenterId,
        userMessage: buildReplyPrompt({ platform, postId, commentText, context, products: context.products, systemPrompt: config.system_prompt || DEFAULT_SYSTEM_PROMPT, isReplyComment }),
        history: [],
        imageUrls: [],
        audioUrls: [],
        config: { ...event.accountConfig, text_prompt: config.system_prompt || DEFAULT_SYSTEM_PROMPT },
        platform
      });
      publicReplyText = cleanReply(result);
      if (publicReplyText) {
        const replyResult = await facebookService.replyToComment(commentId, publicReplyText, accessToken);
        publicStatus = 'sent';
        if (platform === 'messenger' && replyResult?.id) {
          await facebookService.likeComment(replyResult.id, accessToken).catch((error) => errors.push(`reply_like: ${error.message}`));
        }
      }
    } catch (error) {
      publicStatus = 'failed';
      errors.push(`reply: ${error.message}`);
    }
  }

  await updateEvent(platform, commentId, { publicStatus, reactionStatus, reactionType: shouldLike ? 'LIKE' : null, moderationStatus, publicReplyText, decision, errors });
  return { success: errors.length === 0, publicStatus, reactionStatus, moderationStatus, decision, errors };
}

