async function syncFacebookPosts(platform, accountId, accessToken) {
  await ensureTables();
  if (platform !== 'messenger') return { synced: 0, posts: [] };
  const posts = await facebookService.listPagePosts(accountId, accessToken, { limit: 10, maxPages: 5 });
  const saved = [];
  for (const post of posts) {
    const existing = await pgClient.query(
      `SELECT * FROM social_post_product_mappings WHERE platform = $1 AND account_id = $2 AND post_id = $3 LIMIT 1`,
      [platform, String(accountId), String(post.id)]
    );
    const current = existing.rows[0] || {};
    saved.push(await upsertMapping(platform, accountId, {
      post_id: post.id,
      caption: post.message || post.story || current.caption || '',
      media_url: post.full_picture || post.picture || current.media_url || '',
      permalink_url: post.permalink_url || current.permalink_url || '',
      product_ids: current.product_ids || [],
      is_active: current.is_active !== undefined ? current.is_active : true,
      auto_like: Boolean(current.auto_like),
      auto_like_children_comment: Boolean(current.auto_like_children_comment),
      auto_reply: Boolean(current.auto_reply),
      auto_reply_children_comment: Boolean(current.auto_reply_children_comment),
      auto_hidden: Boolean(current.auto_hidden),
      auto_comment: Boolean(current.auto_comment),
      prompt_comment: current.prompt_comment || DEFAULT_PROMPT_COMMENT,
      hide_keywords: current.hide_keywords || [],
      hide_ai_instruction: current.hide_ai_instruction || '',
      hide_ai_enabled: Boolean(current.hide_ai_enabled),
      hide_match_mode: current.hide_match_mode || 'keyword_or_ai',
      post_created_at: post.created_time || current.post_created_at || null
    }));
  }
  return { synced: saved.length, posts: saved };
}

async function findPostContext(platform, accountId, postId) {
  await ensureTables();
  const { rows } = await pgClient.query(`SELECT * FROM social_post_product_mappings WHERE platform = $1 AND account_id = $2 AND post_id = $3 AND is_active = TRUE LIMIT 1`, [platform, String(accountId), String(postId)]);
  let mapping = rows[0] || null;
  if (!mapping && platform === 'messenger') {
    const ad = await dbService.getAdContext(postId, accountId).catch(() => null);
    if (ad) mapping = { post_id: postId, caption: ad.description, product_ids: Array.isArray(ad.linked_product_ids) ? ad.linked_product_ids : [] };
  }
  const products = [];
  for (const id of mapping?.product_ids || []) {
    const product = await dbService.getProductById(id).catch(() => null);
    if (product) products.push(product);
  }
  return { mapping, products };
}

function productSummary(products) {
  if (!products.length) return 'No mapped product found for this post.';
  return products.map((product) => `Product ID: ${product.id}\nName: ${product.name}\nPrice: ${product.price || ''} ${product.currency || ''}\nDescription: ${product.description || ''}`).join('\n\n');
}

function buildReplyPrompt({ platform, postId, commentText, context, products, systemPrompt, isReplyComment }) {
  return `${systemPrompt}\n\n${context.mapping?.prompt_comment || DEFAULT_PROMPT_COMMENT}\n\nReturn only the reply text.\n\n<context>\nPlatform: ${platform}\nPost ID: ${postId}\nIs reply/child comment: ${isReplyComment ? 'yes' : 'no'}\nPost caption: ${context.mapping?.caption || ''}\nCustomer comment: ${commentText}\nMapped products:\n${productSummary(products)}\n</context>`;
}

function cleanReply(value) {
  const text = typeof value === 'string' ? value : (value?.reply_text || value?.reply || value?.message || value?.response || '');
  return String(text || '').replace(/```[\s\S]*?```/g, '').trim().slice(0, MAX_PUBLIC_REPLY_LENGTH);
}

async function evaluateHideRules({ config, mapping, commentText, postId, isReplyComment, accountConfig, platform, accountId, commenterId }) {
  if (!mapping?.auto_hidden) return { shouldHide: false, reason: 'hide_disabled', matchedKeywords: [], mode: 'keyword_or_ai', aiHide: false, aiReason: '' };

  const mode = normalizeHideMode(mapping?.hide_match_mode);
  const keywords = normalizeKeywords([...(config?.hide_keywords || []), ...(mapping?.hide_keywords || [])]);
  const matchedKeywords = keywordMatches(commentText, keywords);
  if (mode === 'all') return { shouldHide: true, reason: 'hide_all_enabled', matchedKeywords, mode, aiHide: false, aiReason: '' };

  let aiHide = false;
  let aiReason = '';
  try {
    const result = await aiService.generateResponse({
      pageId: accountId,
      userId: commenterId || 'comment_moderation',
      userMessage: buildHidePrompt({
        commentText,
        postId,
        isReplyComment,
        caption: mapping?.caption || '',
        globalInstruction: config?.hide_ai_instruction || '',
        postInstruction: mapping?.hide_ai_instruction || '',
        keywords,
        mode
      }),
      history: [],
      imageUrls: [],
      audioUrls: [],
      config: { ...accountConfig, text_prompt: 'You are a strict comment moderation judge. Return only one word: true or false.' },
      platform
    });
    const parsed = parseHideDecision(result);
    aiHide = parsed.hide;
    aiReason = parsed.reason;
  } catch (error) {
    aiReason = `ai_error: ${error.message}`;
  }

  return {
    shouldHide: aiHide,
    reason: aiHide ? 'llm_policy_match' : 'llm_policy_no_match',
    matchedKeywords,
    mode,
    aiHide,
    aiReason
  };
}

